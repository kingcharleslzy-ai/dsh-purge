export function englishText(key, values = {}) {
  const text = en[key];
  if (typeof text !== "string") return key;
  return text.replace(/\{(\w+)\}/g, (placeholder, name) =>
    Object.hasOwn(values, name) ? String(values[name]) : placeholder,
  );
}

export let translate = englishText;

export function setTranslate(t) {
  translate = t;
}

export function useT() {
  return translate;
}

export function compatibilityLevelText(t, level) {
  const key = "compat.level." + (level || "unknown");
  const hit = t(key);
  return hit && hit !== key ? hit : en[key] || level || t("unknown");
}

