export function missingAiBaseMessage() {
  const env = dshBaseEnvStatus();
  if (env.set && !env.valid) {
    return `DSH_BASE is set but is not a valid plugin root (requires dsh-agent-instructions/lib underneath): ${env.path}`;
  }
  const layout = hostLayoutEvidence("");
  if (layout.family === "tauri") return layout.note;
  if (adapterFor(detectSurface()) === "desktop") {
    const exe = desktop.findDesktopAppExecutable();
    if (exe) {
      const asar = desktop.appAsarPath(exe);
      const recovery = desktop.appDirForExecutable(exe) + ".dshpurge-recover.json";
      if (hostFs.existsSync(recovery)) return `Last desktop directory swap failed; recovery record: ${recovery}. Check the failed path and system error code.`;
      if (asarArchiveIsFile(asar) && desktop.isOfficialHarnessExecutable(exe)) {
        return `Found ${exe}. The official host is inside app.asar; clicking "Apply" will unpack ${desktop.appDirForExecutable(exe)} and restart automatically, no separate script needed.`;
      }
      return `Found desktop app ${exe}, but @deepseek-ai was not found under its resources/app (or app.asar.unpacked)`;
    }
    return "Could not locate @deepseek-ai for the current desktop app. In the official client click \"Apply\" to unpack app.asar and restart; in third-party DSH Desktop click \"Apply\" directly. The install directory can be on any drive." ;
  }
  if (env.valid) return `DSH_BASE host directory validated (${env.path}), but the current ${detectSurface()} runtime could not locate the plugin root.`;
  return `Could not locate the host @deepseek-ai directory in the current ${detectSurface()} runtime.`;
}

