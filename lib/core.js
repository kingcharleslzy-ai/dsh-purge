function findAiBaseRecursive(root, needle, depth, visited, rootDev) {
  if (depth > 6) return null;
  // H21: realpath + Set to prevent symlink cycles, otherwise pnpm/junction environments can blow the stack.
  const seen = visited || new Set();
  let real;
  try { real = fs.realpathSync.native(root); } catch { real = root; }
  const key = String(real).replace(/\\/g, "/").toLowerCase();
  if (seen.has(key)) return null;
  seen.add(key);
  // #91: record root device id on first call; do not cross devices when descending with readdir - cloud/NFS/SMB readdir per level
  // is a network round trip; huge directory trees under mount points (e.g. macFUSE CloudDrive) can hang apply() forever.
  if (rootDev === undefined) {
    try { rootDev = fs.statSync(root).dev; } catch { rootDev = null; }
  }
  let entries;
  try {
    entries = fs.readdirSync(root, { withFileTypes: true });
  } catch {
    return null;
  }
  for (const e of entries) {
    if (!e.isDirectory()) continue;
    const child = path.join(root, e.name);
    // #91: do not descend across mount points - enumerating thousands of local directories is fine, stepping into cloud storage hangs
    // F15: on Windows cross-device can only happen at reparse points (symlinks/junctions/volume mount points),
    // calling statSync for dev on every normal subdirectory is wasteful - ~7.2s for 60k dirs, half the fallback scan cost.
    // Non-Windows mount points are not symlinks; keep the original check.
    if (rootDev !== null && (process.platform !== "win32" || e.isSymbolicLink())) {
      let childDev;
      try { childDev = fs.statSync(child).dev; } catch { continue; }
      if (childDev !== rootDev) continue;
    }
    if (e.name === "node_modules") {
      const nestedHit = path.join(root, needle);
      if (isAiBase(nestedHit)) return path.normalize(nestedHit);
      const flatHit = path.join(root, "node_modules", "@deepseek-ai");
      if (isAiBase(flatHit)) return path.normalize(flatHit);
      if (isPnpmNodeModules(path.join(root, "node_modules"))) {
        const pnpmHit = firstAiBase(pnpmHoistAiBases(root));
        if (pnpmHit) return pnpmHit;
      }
    }
    const sub = findAiBaseRecursive(child, needle, depth + 1, seen, rootDev);
    if (sub) return sub;
  }
  return null;
}

