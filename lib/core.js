// Earlier Web installations used the desktop cookie name. Reverse only our
// uniquely marked expression; never replace the whole authentication module.
async function legacyWebCookieStatus(files, patch, repair) {
  const rows = [];
  const { pattern, replace } = patch.replacements[0];
  for (const fp of pathsOf(files, patch.file)) {
    try {
      const source = await loadText(fp);
      if (!source.includes(patch.marker)) continue;
      if (source.split(patch.marker).length !== 2 || !source.includes(replace))
        throw Error("unrecognized legacy cookie-name expression");
      if (repair) await saveText(fp, source.replace(replace, () => pattern));
      rows.push({ path: fp, status: repair ? "restored" : "pending" });
    } catch (error) { rows.push({ path: fp, status: "unmatched", error: error.message }); }
  }
  return rows;
}

