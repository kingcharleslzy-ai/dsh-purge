async function loadText(p) {
  return fsp.readFile(p, "utf8");
}

async function saveText(p, text, expected) {
  const next = Buffer.from(text, "utf8");
  try {
    const current = await fsp.readFile(p);
    if (current.equals(next)) return false;
    if (expected !== undefined && !current.equals(Buffer.from(expected))) throw Error("permission target changed during migration");
  } catch (e) {
    if (expected !== undefined || !e || e.code !== "ENOENT") throw e;
  }
  // H19: atomic write; do not leave half-written files on power loss/EBUSY.
  await atomicWriteFile(p, next);
  return true;
}

