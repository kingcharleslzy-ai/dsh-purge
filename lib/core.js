function filterTargetFiles(files) {
  const out = {};
  for (const [key, val] of Object.entries(files)) {
    if (Array.isArray(val)) {
      const kept = val.filter((fp) => !fp || !fs.existsSync(fp) || allowTargetForPatch(fp));
      const existing = kept.filter((fp) => fp && fs.existsSync(fp) && allowTargetForPatch(fp));
      out[key] = existing.length ? existing : [];
    } else if (val && fs.existsSync(val) && !allowTargetForPatch(val)) {
      out[key] = "";
    } else {
      out[key] = val;
    }
  }
  // Do not register keys that resolve to nothing. Those ✗ rows in the status panel look like "something was not cleaned up",
  // but in reality this layout simply does not have that file (preset-unrestricted, *-nested, etc.).
  // Downstream pathsOf() returns [] for missing keys, same behavior as registering "".
  for (const key of Object.keys(out)) {
    const val = out[key];
    if (val === "" || (Array.isArray(val) && val.length === 0)) delete out[key];
  }
  return out;
}

