function filePatchSettled(text, patch, fp = "") {
  if (patchApplied(text, patch)) return true;
  // When official copy layout differs or approval sentences were rewritten by 0.1.5, absence of residual patterns counts as complete.
  if (isLayoutSoftPatch(patch)) return !patchHasRemainingWork(text, patch, fp);
  return false;
}

function selfMarkedPatch(patch) {
  // Revert/self-marking patches: the pattern itself is a trace written by the plugin; not found means never added or already reverted.
  return patchReplacements(patch).some(({ pattern }) =>
    typeof pattern === "string" && pattern.includes("[dsh-purge]"));
}

function filePatchOutcome(text, patch, fp = "") {
  if (filePatchSettled(text, patch, fp)) return "applied";
  if (patchHasRemainingWork(text, patch, fp)) return "pending";
  // File exists, marker missing, no anchors match: this is drift after host revision, not "skipped".
  // Previously this silently became skipped and treated as soft success; after official upgrades the plugin would silently stop working while status stayed green.
  // For a few patches, "not found" is itself the correct state (e.g. user presets that never had the official identity line).
  if (patch.silentWhenMissing) return "skipped";
  if (!selfMarkedPatch(patch)) return "drifted";
  return "skipped";
}


