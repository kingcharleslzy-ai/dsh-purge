/**
 * Pure decision for "how to restart after Apply", for easier unit testing:
 * - sealed: the current process can confirm the archive is still sealed;
 * - foreign: not visible from the current surface, but the desktop installation archive is still sealed;
 * - desktopPid: whether the desktop host is running (>0 means we can wait for it to exit).
 */
export function planApplyRestartAction({ sealed = false, foreign = null, desktopPid = 0 } = {}) {
  if (sealed) return { action: "swap" };
  if (foreign && foreign.asar && desktopPid) return { action: "swap-foreign", waitPid: desktopPid };
  if (foreign && foreign.asar) return { action: "manual", reason: "Desktop host is not running; cannot swap package after it exits" };
  return { action: "plain" };
}

