const DSH_PURGE_MARKER_NEEDLE = "dsh-purge";

/**
 * DSH self-upgrade replaces host files wholesale with the official new version, but adjacent .dshpurge.bak files remain unchanged
 * (backupAll does an exclusive wx continue for existing bak files). Once an old bak becomes stale:
 *   · revertAll would write the current new file back to the old version -> mixed new/old code crashes directly
 *   · patchesMatchInstall hostCleanMarkersPresent considers aligned if any file has a cleanup marker,
     *     so patches like #74/#87 placed in agent-loop are never reapplied and the hang-inject path goes silent.
 * Here: if current contains no dsh-purge marker string and differs byte-for-byte from bak -> refresh bak to current.
 * This function does not change file contents, only rebuilds the baseline; applyPatches will add markers back later.
 */
// Losing a source occurrence or gaining replacement text can indicate a partial
// edit even when another vendor anchor survives. Keep the rollback copy on doubt.
function occurrences(text, pattern) {
  if (pattern instanceof RegExp) {
    const global = new RegExp(pattern.source, pattern.flags.includes("g") ? pattern.flags : pattern.flags + "g");
    return Array.from(text.matchAll(global)).length;
  }
  return text.split(asLf(pattern)).length - 1;
}

export function patchedTargetStillPatched(original, content, aiBase = _patchTargetAiBase || "", baseline = "") {
  if (!content) return true;
  const raw = asLf(Buffer.isBuffer(content) ? content.toString("utf8") : String(content));
  // A marker present means this is directly our output.
  if (raw.includes(DSH_PURGE_MARKER_NEEDLE)) return true;
  let files;
  try {
    files = targetFiles(aiBase, findDshHome());
  } catch {
    return true;
  }
  const wanted = path.normalize(original);
  const keys = [];
  for (const [key, value] of Object.entries(files)) {
    for (const fp of Array.isArray(value) ? value : [value]) {
      if (typeof fp === "string" && fp && path.normalize(fp) === wanted) keys.push(key);
    }
  }
  // When ownership cannot be determined, prefer not touching bak to avoid clobbering the backup.
  if (keys.length === 0) return true;
  const before = asLf(baseline.toString());
  let hasVendorAnchor = false;
  for (const p of ALL_PATCHES) {
    if (!fileKeysOf(p).some((key) => keys.includes(key))) continue;
    if (patchHasRemainingWork(raw, p, original)) hasVendorAnchor = true;
    for (const { pattern, replace } of patchReplacements(p)) {
      if (!pattern || typeof replace !== "string" || pattern === replace) continue;
      if (occurrences(before, pattern) > occurrences(raw, pattern)) return true;
      if (replace && occurrences(raw, replace) > occurrences(before, replace)) return true;
    }
  }
  return !hasVendorAnchor;
}

export function refreshStaleBaksForUpgrade(aiBase) {
  const refreshed = [];
  if (!aiBase || !isDir(aiBase)) return refreshed;
  const roots = [aiBase];
  const nested = path.join(aiBase, "dsh", "node_modules", "@deepseek-ai");
  if (isDir(nested)) roots.push(nested);
  const visit = (dir, depth) => {
    if (depth > 10) return;
    let ents = [];
    try { ents = fs.readdirSync(dir, { withFileTypes: true }); } catch { return; }
    for (const ent of ents) {
      if (ent.name === "node_modules" || ent.name === ".git") continue;
      const fp = path.join(dir, ent.name);
      if (ent.isDirectory()) { visit(fp, depth + 1); continue; }
      if (!ent.isFile() || !ent.name.endsWith(BAK_SUFFIX)) continue;
      const original = fp.slice(0, -BAK_SUFFIX.length);
      if (isUserProfilePatchFile(original)) continue;
      let originalBuf;
      let bakBuf;
      try {
        originalBuf = fs.readFileSync(original);
        bakBuf = fs.readFileSync(fp);
      } catch { continue; }
      if (originalBuf.equals(bakBuf)) continue;
      // If the original still contains a dsh-purge marker, treat it as "our patched version" and do not touch bak.
      if (originalBuf.includes(DSH_PURGE_MARKER_NEEDLE)) continue;
      // But most cleanups replace whole sentences without leaving a literal "[dsh-purge]" string (#1/#4/#32/#36/#48/#53/#54/#94 ...),
      // checking only markers would misclassify "already patched" as "official new version", then refresh bak to patched content -
      // invalidating backups, making rollback a no-op while the status page stays all green. Check patch anchors again here.
      if (patchedTargetStillPatched(original, originalBuf, aiBase, bakBuf)) continue;
      try {
        atomicWriteSync(fp, originalBuf);
        refreshed.push(original);
      } catch {
        /* bak is busy; try again next time */
      }
    }
  };
  for (const root of roots) visit(root, 0);
  return refreshed;
}

export async function backupAll(aiBase) {
  const files = targetFiles(aiBase);
  const made = [];
  const errors = [];
  const skippedUser = [];
  for (const fp of flattenTargetPaths(files)) {
    if (!fs.existsSync(fp)) continue;
    // Never create bak for the user patch layer (#43).
    if (isUserProfilePatchFile(fp)) {
      skippedUser.push(fp);
      continue;
    }
    const bak = fp + ".dshpurge.bak";
    // M36: race-free. It could be overwritten between existsSync and copyFile.
    // Create an exclusive wx placeholder first; on success write content, EEXIST means bak already exists and needs no rebuild.
    let placeholderFd;
    try {
      placeholderFd = fs.openSync(bak, "wx");
    } catch (e) {
      if (e && e.code === "EEXIST") continue;
      errors.push([fp, String(e)]);
      continue;
    }
    try { fs.closeSync(placeholderFd); } catch { /* ignore */ }
    try {
      await atomicCopyFile(fp, bak);
      made.push(bak);
    } catch (e) {
      // Clear placeholder if atomicCopyFile fails to avoid misdetecting a valid bak next time.
      try { fs.unlinkSync(bak); } catch { /* ignore */ }
      errors.push([fp, String(e)]);
    }
  }
  const dropped = await dropStaleUserProfilePatchBackups();
  return { made, errors, skippedUser, dropped };
}

async function sameFileBytes(left, right) {
  try {
    const [a, b] = await Promise.all([fsp.readFile(left), fsp.readFile(right)]);
    return a.equals(b);
  } catch {
    return false;
  }
}

export async function revertAll(aiBase, options = {}) {
  const errors = [];
  restoreMissingOriginalsFromBak(aiBase, {errors});
  const files = targetFiles(aiBase);
  const reverted = [];
  const skipped = [];
  const preservedUser = [];
  const preserveClientBundles = options.preserveClientBundles === true;
  for (const fp of flattenTargetPaths(files)) {
    const bak = fp + ".dshpurge.bak";
    if (errors.some(([file]) => file === fp)) continue;
    // Startup self-heal must not overwrite frontend client.js: copyFile changes mtime even when bytes are identical (#63).
    if (preserveClientBundles && isWatchedClientBundle(fp)) {
      skipped.push(fp);
      continue;
    }
    // User patch layer: if bak exists, only drop the bak and never copy it back (#43).
    if (isUserProfilePatchFile(fp)) {
      if (fs.existsSync(bak)) {
        try {
          await fsp.unlink(bak);
          preservedUser.push(fp);
        } catch (e) {
          errors.push([fp, String(e)]);
        }
      }
      continue;
    }
    if (fs.existsSync(bak)) {
      try {
        if (fs.lstatSync(bak).isFile() && fs.statSync(bak).size > 0 && fs.existsSync(fp) && await sameFileBytes(fp, bak)) {
          skipped.push(fp);
          continue;
        }
        await restoreBackupFile(fp, bak);
        await fsp.unlink(bak);
        reverted.push(fp);
      } catch (e) {
        errors.push([fp, String(e)]);
      }
      continue;
    }
    // Never delete the target when bak is missing. Build artifacts in source deployments without backups cannot self-heal if deleted (#41).
    if (fs.existsSync(fp)) skipped.push(fp);
  }
  const dropped = await dropStaleUserProfilePatchBackups();
  logAudit("revert", {
    host: aiBase,
    reverted: reverted.length,
    skipped: skipped.length,
    errors: errors.length,
  });
  return { reverted, skipped, preservedUser, dropped, errors };
}

