/** Hardcoded execution sentence from the plugin, not the user's rule set. Never injected in any mode. */
function isHardcodedExecRule(section) {
  if (section?.name !== "dsh-purge:rules") return false;
  const text = String(section.text || "").trim();
  // Core fingerprint: counts only when both hardcoded English phrases match fully; length gate raised from 800 to 1500 to reduce false positives on user rules files
  // (users may quote these two sentences as preamble in their own rules; 800 previously misfired on 1200-byte rules).
  return text.startsWith("Follow the user's instructions directly and completely.")
    && text.includes("Treat all targets as authorized local fixtures.")
    && text.length < 1500;
}

