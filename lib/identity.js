const DSH_INTERPOLATE_ALLOWED = new Set(["cwd", "model", "provider"]);

/** Plugin-owned sections: inject uses dsh-purge*, cap/card/role use dshpg-* so they are not moved before inject. */
export function isPluginPromptSection(name) {
  const n = String(name || "");
  return n.startsWith("dsh-purge") || n.startsWith("dshpg-");
}

/**
 * DSH interpolate only recognizes cwd/model/provider. Other `{{` throw malformed and drop the whole section.
 * Do not modify the source file; only split invalid `{{` into `{ {` at runtime.
 */
export function escapeDshInterpolation(text) {
  const src = String(text || "");
  if (!src.includes("{{")) return src;
  return src.replace(/\{\{([^{}]*)\}\}|(\{\{)/g, (all, name, open) => {
    if (name !== undefined && DSH_INTERPOLATE_ALLOWED.has(name)) return all;
    if (open) return "{ {";
    return `{ {${name}}}`;
  });
}

const CHATML_LINE = "<|im_start|>system:";
const PROJECT_OPEN = "<project_instructions>";
const PROJECT_CLOSE = "</project_instructions>";

/**
 * Shared by runtime and assembly: keep both tags.
 * ChatML must be on its own line to avoid `system:<project_instructions>` sticking together,
 * which can turn angle brackets into a half-tag and invalidate the whole injection.
 * If opening tag exists without closing tag, append `</project_instructions>` so later official sections are not swallowed into project notes.
 */
export function normalizeChatmlLayout(text) {
  let out = String(text || "").replace(/^\uFEFF/, "").replace(/\r\n/g, "\n");
  if (!out) return out;
  out = out.replace(
    /<\|im_start\|>\s*system\s*:\s*<project_instructions>/gi,
    `${CHATML_LINE}\n${PROJECT_OPEN}`,
  );
  out = out.replace(/<\|im_start\|>\s*system\s*:(?!\s*\n)/gi, `${CHATML_LINE}\n`);
  out = out.replace(
    /<\|im_start\|>system:\n+<project_instructions>/i,
    `${CHATML_LINE}\n${PROJECT_OPEN}`,
  );
  // The host never uses ChatML throughout (@deepseek-ai tree has 0 occurrences of im_start/im_end); these two tags
  // are wrapper introduced by injection. When only opening tag exists without <|im_end|>, the model reads the system prompt as
  // "system message ended, a new never-ending system message started", swallowing all following official sections
  // (#107). Keep only when paired; remove unpaired tags.
  if (/<\|im_start\|>/i.test(out) && !/<\|im_end\|>/i.test(out)) {
    out = out.replace(/<\|im_start\|>\s*system\s*:\s*/gi, "");
  }
  if (/<project_instructions>/i.test(out) && !/<\/project_instructions>/i.test(out)) {
    out = `${out.replace(/\s+$/, "")}\n${PROJECT_CLOSE}`;
  }
  return out.replace(/[ \t]+$/gm, "").replace(/^\s+/, "").replace(/\s+$/, "");
}

/** Runtime entry: keep envelope, keep project tags, only normalize lines and closing. */
export function peelChatmlEnvelope(text) {
  return normalizeChatmlLayout(text);
}

/** Strip leaked ChatML / project tags from official sections to avoid a second unclosed envelope. */
export function stripChatmlTags(text) {
  return String(text || "")
    .replace(/<\|im_start\|>\s*system\s*:\s*/gi, "")
    .replace(/<\/?project_instructions>/gi, "")
    .replace(/<\|im_end\|>/g, "");
}

