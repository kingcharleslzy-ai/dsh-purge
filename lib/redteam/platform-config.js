/**
 * Red-team platform adaptation config (in-plugin, no .ps1)
 *
 * On disk: `$DSH_HOME/redteam/config.json`
 * Purpose:
 *   · on Windows / non-Kali machines, the user supplies absolute tool paths or search directories
 *   · preflight / skill availability / nuclei template dir all read from here
 *   · nothing is ever written into the official `$DSH_HOME/skills`
 *
 * Borrowed from Z3r0: system config lives in one place and is editable in the UI (FOFA / paths),
 * not reachable only through shell bootstrap.
 */
import { closeSync, existsSync, mkdirSync, openSync, readFileSync, readSync, readdirSync, statSync } from 'node:fs'
import { atomicWriteFileSync } from './atomic-write.js'
import { homedir, platform as osPlatform } from 'node:os'
import { delimiter, isAbsolute, join, resolve, sep } from 'node:path'

/** Config file path. */
export function configPathOf(root) {
  return join(root || redteamRoot(), 'config.json')
}

export function redteamRoot() {
  const home = process.env.DSH_HOME || join(homedir(), '.dsh')
  return join(home, 'redteam')
}

/** Default toolkit directory. */
export function defaultToolkitDir(root) {
  return join(root || redteamRoot(), 'toolkit')
}

